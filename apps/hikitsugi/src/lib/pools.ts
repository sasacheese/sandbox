/**
 * 引継書の材料。
 *
 * ここの質がこの作品の質そのもの。守っている規則が 3 つある。
 *
 * 1. **秘密は重い。** 「好きな食べ物」の類は入れない。打ち明けるのに勇気が要る
 *    ものだけを置く。預かってしまった感じが出ないと、引き継ぎが軽くなる。
 * 2. **作り話は、確かめようがない形にする。** 「猫を飼っている」「父を早く
 *    亡くした」——訂正しようとすると関係の側が壊れる種類の嘘。
 * 3. **内輪のネタには意味を書き添える。** 意味を知らないと使えないが、
 *    意味を教わって使うネタは、もう内輪ではない。そのねじれを書類で見せる。
 */

